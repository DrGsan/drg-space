import {appSection,editorMode,newNote} from './notes-ui.js';
import {expect} from '@playwright/test';
import {unlockDashboard} from './widget-edit-flow.js';
import {assertCodeTheme} from './code-theme-flow.js';
export async function dashboardUpdateFlow(page){
  await appSection(page, 'Настройки');
  await page.getByLabel('Режим оформления').selectOption('system');
  await page.getByRole('button',{name:'Сохранить оформление'}).click();
  await appSection(page, 'Главная');
  const notes=async()=>await (await page.request.get('/api/notes')).json();
  const before=(await notes()).length;
  await newNote(page);
  await page.getByLabel('Название заметки').fill('   ');
  await editorMode(page, 'Markdown');
  await page.getByLabel('Текст заметки в Markdown').fill('  \n ');
  await appSection(page, 'Главная');
  expect((await notes()).length).toBe(before);
  // First POST held in flight; a later edit must still be saved.
  await newNote(page);
  let release,started;
  const held=new Promise(r=>release=r),pending=new Promise(r=>started=r);
  let first=true;
  const slow=async route=>{if(route.request().method()==='POST'&&first){first=false;started();await held;}await route.continue();};
  await page.route('**/api/notes',slow);
  await page.getByLabel('Название заметки').fill('Черновик с кодом');
  await pending;
  await editorMode(page, 'Markdown');
  await page.getByLabel('Текст заметки в Markdown').fill('```python\ndef greet(name):\n    return "Hello " + name\n```');
  release();await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  await page.unroute('**/api/notes',slow);
  await editorMode(page, 'Блоки');
  const language=page.getByLabel('Язык кода');await expect(language).toHaveValue('python');
  await expect.poll(()=>page.locator('code span[style*="--shiki-light"]').count()).toBeGreaterThan(1);
  const colors=()=>page.locator('code span[style*="--shiki-light"]').evaluateAll(items=>items.map(el=>getComputedStyle(el).color));
  const lightColors=await colors();expect(new Set(lightColors).size).toBeGreaterThan(1);
  await assertCodeTheme(page);
  await page.screenshot({path:'artifacts/notes-code-light.png',fullPage:true});
  await page.emulateMedia({colorScheme:'dark'});await expect(page.locator('html')).toHaveAttribute('data-scheme','dark');
  expect(await colors()).not.toEqual(lightColors);await assertCodeTheme(page);await page.screenshot({path:'artifacts/notes-code-dark.png',fullPage:true});await page.emulateMedia({colorScheme:'light'});
  await language.selectOption('sql');
  await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  await page.reload();await expect(language).toHaveValue('sql');
  const id=new URL(page.url()).pathname.split('/').at(-1);
  const saved=await (await page.request.get('/api/notes/'+id)).json();expect(saved.blocks[0].props.language).toBe('sql');
  // Unrecognized imported fence languages stay editable without a crash.
  await editorMode(page, 'Markdown');
  await page.getByLabel('Текст заметки в Markdown').fill('```custom-language\nhello\n```');
  await editorMode(page, 'Блоки');
  await expect(language).toHaveValue('custom-language');
  await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  await page.locator(`[data-open-page="${id}"]`).first().click({button:'right'});
  await expect(page.getByRole('menu')).toBeVisible();
  page.once('dialog',d=>d.accept());await page.getByRole('menuitem',{name:'Удалить в корзину'}).click();
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect.poll(async()=>(await notes()).some(n=>n.id===id)).toBe(false);
  await appSection(page, 'Настройки');
  await page.getByLabel('Аватар', {exact:true}).setInputFiles('tests/fixtures/blue.png');
  await expect(page.locator('[data-avatar-status]')).toHaveText('Аватар сохранён');
  await expect.poll(()=>page.locator('.user .avatar img').evaluate(img=>img.naturalWidth)).toBe(256);
  await page.reload();await expect(page.locator('.user .avatar img')).toHaveCount(1);
  await appSection(page, 'Настройки');
  await page.getByRole('button',{name:'Убрать аватар'}).click();await expect(page.locator('.user .avatar img')).toHaveCount(0);
  await page.emulateMedia({colorScheme:'dark'});
  await page.getByLabel('Режим оформления').selectOption('system');await expect(page.locator('html')).toHaveAttribute('data-scheme','dark');
  await page.emulateMedia({colorScheme:'light'});await expect(page.locator('html')).toHaveAttribute('data-scheme','light');
  await page.getByRole('button',{name:'Сохранить оформление'}).click();
  await appSection(page, 'Главная');
}

export async function widgetSizingFlow(page){
  const rss=page.locator('[data-widget=rss]');
  await unlockDashboard(page);
  await rss.locator('[data-configure]').click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Размер',{exact:true}).selectOption('2x3');
  await dialog.getByRole('button',{name:'Сохранить виджет'}).click();
  await page.route('**/api/widgets/*/rss',route=>route.fulfill({json:{items:Array.from({length:50},(_,i)=>({title:'Длинный заголовок новости '+i+' — подробное описание события',url:'https://example.com/'+i,source:'Источник',published:0})),errors:[]}}));
  await page.reload();await expect(rss.locator('.rss-item')).toHaveCount(50);
  const box=await rss.boundingBox(),cell=await page.locator('#widget-grid').evaluate(el=>Number.parseFloat(el.style.getPropertyValue('--grid-cell')));
  expect(Math.abs(box.height-(cell*3+32))).toBeLessThan(2);
  const body=await rss.locator('[data-widget-body]').evaluate(el=>({scroll:el.scrollHeight,client:el.clientHeight,overflow:getComputedStyle(el).overflowY}));
  expect(body.scroll).toBeGreaterThan(body.client);expect(body.overflow).toBe('auto');
  const calendar=await page.locator('[data-widget=calendar]').boundingBox();expect(Math.abs(calendar.height-cell)).toBeLessThan(2);
  await unlockDashboard(page);await rss.locator('[data-configure]').click();await dialog.getByLabel('Размер',{exact:true}).selectOption('1x1');await dialog.getByRole('button',{name:'Сохранить виджет'}).click();
  await expect(rss).toHaveClass(/widget-1x1/);
  expect(Math.abs((await rss.boundingBox()).height-cell)).toBeLessThan(2);
  await page.setViewportSize({width:390,height:844});expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/dashboard-grid-mobile.png',fullPage:true});
  await page.setViewportSize({width:1280,height:900});await page.screenshot({path:'artifacts/dashboard-grid-desktop.png',fullPage:true});
  await page.unroute('**/api/widgets/*/rss');
}
