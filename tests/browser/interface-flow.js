import {appSection,editorMode,newNote} from './notes-ui.js';
import {expect} from '@playwright/test';

export async function interfaceFlow(page){
  const lock=()=>page.locator('#dashboard-lock');
  const original=await page.locator('[data-widget]').evaluateAll(items=>items.map(item=>item.dataset.widgetId));
  await expect(lock()).toHaveAttribute('aria-pressed','false');
  await expect(page.locator('[data-move-widget]').first()).toBeHidden();
  await lock().click();await expect(lock()).toHaveAttribute('aria-pressed','true');
  const source=page.locator('[data-widget]').last().locator('[data-move-widget]');
  const target=page.locator('[data-widget]').first();
  // Real native drag, with a pointer position in the target's first half.
  await source.dragTo(target,{targetPosition:{x:20,y:20}});
  await expect(page.locator('[data-widget]').first()).toHaveAttribute('data-widget-id',original.at(-1));
  await expect(page.locator('[data-layout-status]')).toHaveText('Порядок сохранён');
  const persisted=(await (await page.request.get('/api/dashboard/layout')).json()).instances.map(item=>item.id);
  expect(persisted[0]).toBe(original.at(-1));
  await appSection(page, 'Настройки');
  await appSection(page, 'Главная');
  await expect(lock()).toHaveAttribute('aria-pressed','false');
  await expect(page.locator('[data-widget]').first()).toHaveAttribute('data-widget-id',original.at(-1));
  await lock().click();await page.reload();await expect(lock()).toHaveAttribute('aria-pressed','false');
  await lock().click();
  await page.locator('[data-widget]').first().locator('[data-move-widget]').press('ArrowDown');
  await page.locator('[data-widget]').nth(1).locator('[data-move-widget]').press('ArrowDown');
  await expect(page.locator('[data-layout-status]')).toHaveText('Порядок сохранён');
  expect(await page.locator('[data-widget]').evaluateAll(items=>items.map(item=>item.dataset.widgetId))).toEqual(original);
  // Actual touch input exercises pointer capture rather than synthetic DOM events.
  const cdp=await page.context().newCDPSession(page);
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:true});
  const grip=await page.locator('[data-widget]').first().locator('[data-move-widget]').boundingBox();
  const destination=await page.locator('[data-widget]').nth(1).boundingBox();
  await cdp.send('Input.dispatchTouchEvent',{type:'touchStart',touchPoints:[{x:grip.x+grip.width/2,y:grip.y+grip.height/2}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchMove',touchPoints:[{x:destination.x+destination.width-50,y:destination.y+50}]});
  await cdp.send('Input.dispatchTouchEvent',{type:'touchEnd',touchPoints:[]});
  await expect(page.locator('[data-widget]').first()).toHaveAttribute('data-widget-id',original[1]);
  await expect(page.locator('[data-layout-status]')).toHaveText('Порядок сохранён');
  await cdp.send('Emulation.setTouchEmulationEnabled',{enabled:false});await cdp.detach();
  await page.locator('[data-widget]').nth(1).locator('[data-move-widget]').press('ArrowUp');
  await expect(page.locator('[data-layout-status]')).toHaveText('Порядок сохранён');
  await page.screenshot({path:'artifacts/dashboard-unlocked.png',fullPage:true});
  await appSection(page, 'Настройки');
  await page.getByRole('radio',{name:'Лаванда',exact:true}).check();
  await expect(page.locator('html')).toHaveAttribute('data-theme','lilac');
  expect((await (await page.request.get('/api/appearance')).json()).preferences.theme).toBe('ocean');
  expect(await page.evaluate(()=>JSON.parse(localStorage.getItem('drg-appearance')).theme)).toBe('ocean');
  await page.getByLabel('Режим оформления').selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-scheme','dark');
  await appSection(page, 'Главная');
  await expect(page.locator('html')).toHaveAttribute('data-theme','ocean');
  await expect(page.locator('html')).toHaveAttribute('data-scheme','light');
  await appSection(page, 'Настройки');
  await page.getByRole('radio',{name:'Лес',exact:true}).check();
  await page.getByRole('button',{name:'Сохранить оформление'}).click();
  await expect.poll(async()=>((await (await page.request.get('/api/appearance')).json()).preferences.theme)).toBe('sage');
  await page.reload();await expect(page.locator('html')).toHaveAttribute('data-theme','sage');
  await appSection(page, 'Настройки');
  await page.getByRole('radio',{name:'Океан',exact:true}).check();await page.getByRole('button',{name:'Сохранить оформление'}).click();
  await newNote(page);
  await expect(page.locator('.workspace')).toHaveClass(/notes-open/);
  await expect(page.locator('.sidebar')).toHaveCount(0);
  await expect(page.locator('#notes-main-menu')).toBeVisible();
  await expect(page.locator('.topbar')).toHaveCount(0);
  await expect(page.locator('#open-inbox svg')).toBeVisible();
  await expect(page.locator('#open-inbox .notification-label')).toHaveCount(0);
  await expect(page.locator('#pages-sidebar')).toHaveCSS('width','220px');
  await expect(page.locator('#notion-page')).toHaveCSS('border-top-width','0px');
  await expect(page.locator('#discussions-panel')).not.toHaveAttribute('open','');
  await expect(page.getByRole('button',{name:'Сохранить',exact:true})).toHaveCount(0);
  await page.getByLabel('Название заметки').fill('Автосохранение без кнопок');
  await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  await editorMode(page, 'Markdown');
  // Edits typed while the first PUT is still pending must not disappear.
  let started,release;
  const firstStarted=new Promise(resolve=>started=resolve),held=new Promise(resolve=>release=resolve);
  let first=true;
  const slow=async route=>{if(route.request().method()==='PUT'&&first){first=false;started();await held;}await route.continue();};
  await page.route('**/api/notes/*',slow);
  await page.getByLabel('Текст заметки в Markdown').fill('Первая версия');await expect.poll(()=>first).toBe(false);await firstStarted;
  await page.getByLabel('Текст заметки в Markdown').fill('Последняя версия, напечатанная во время сохранения');release();
  await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  const url=page.url(),id=new URL(url).pathname.split('/').at(-1);
  expect((await (await page.request.get('/api/notes/'+id)).json()).body).toContain('Последняя версия');
  await page.unroute('**/api/notes/*',slow);
  await page.getByRole('button',{name:'Свернуть меню заметок'}).click();
  await expect(page.locator('#pages-sidebar')).toBeHidden();
  await expect(page.locator('.notes-workspace')).toHaveClass(/pages-collapsed/);
  await expect(page.locator('.breadcrumbs')).toContainText('Автосохранение без кнопок');
  await expect(page.locator('#toast')).not.toHaveClass(/show/,{timeout:7000});
  await page.screenshot({path:'artifacts/notes-focused.png',fullPage:true});
  await page.getByRole('button',{name:'Показать меню заметок'}).click();await expect(page.locator('#pages-sidebar')).toBeVisible();
  await page.locator('#discussions-panel > summary').click();await expect(page.getByLabel('Комментарий',{exact:true})).toBeVisible();
  await page.locator('#discussions-panel > summary').click();await expect(page.getByLabel('Комментарий',{exact:true})).toBeHidden();
  // A save error keeps the draft and prevents navigation until retry succeeds.
  let fail=true;
  const failure=async route=>{if(fail&&route.request().method()==='PUT')await route.fulfill({status:503,json:{detail:'Тестовый обрыв соединения'}});else await route.continue();};
  await page.route('**/api/notes/*',failure);
  await page.getByLabel('Текст заметки в Markdown').fill('Текст не должен потеряться при ошибке');
  await expect(page.locator('#page-save-status')).toHaveText('Не удалось сохранить');
  await page.locator('#notes-main-menu').click();await expect(page.getByLabel('Текст заметки в Markdown')).toHaveValue('Текст не должен потеряться при ошибке');
  fail=false;await page.getByRole('button',{name:'Повторить сохранение',exact:true}).click();await expect(page.locator('#page-save-status')).toHaveText('Сохранено');
  await page.unroute('**/api/notes/*',failure);
  await page.reload();await expect(page.getByLabel('Название заметки')).toHaveValue('Автосохранение без кнопок');
  await expect(page.getByRole('textbox',{name:'Содержимое страницы'})).toContainText('не должен потеряться');
  await expect(page.locator('#discussions-panel')).not.toHaveAttribute('open','');
  await page.setViewportSize({width:768,height:844});
  await expect(page.locator('#pages-sidebar')).toBeHidden();
  await page.getByRole('button',{name:'Показать меню заметок'}).click();
  const drawer=await page.locator('#pages-sidebar').boundingBox();
  expect(drawer.y+drawer.height).toBeLessThanOrEqual(844);
  await page.setViewportSize({width:390,height:844});
  if(await page.locator('#pages-sidebar').isVisible())await page.getByRole('button',{name:'Свернуть меню заметок'}).click();
  await expect(page.locator('#pages-sidebar')).toBeHidden();
  await page.getByRole('button',{name:'Показать меню заметок'}).click();
  await expect(page.locator('#pages-sidebar')).toBeVisible();
  await page.getByLabel('Поиск заметок').focus();await page.keyboard.press('Escape');
  await expect(page.locator('#pages-sidebar')).toBeHidden();
  await expect(page.getByRole('button',{name:'Показать меню заметок'})).toBeFocused();
  await page.getByRole('button',{name:'Показать меню заметок'}).click();
  await page.locator('#pages-tools > summary').click();await page.getByRole('button',{name:'Новая база',exact:false}).click();
  await expect(page.getByLabel('Название базы')).toBeVisible();await page.getByRole('button',{name:'Закрыть',exact:true}).click();
  await expect(page.locator('#pages-sidebar')).toBeHidden();await expect(page.getByRole('button',{name:'Показать меню заметок'})).toBeFocused();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'artifacts/notes-focused-mobile.png',fullPage:true});
  await page.setViewportSize({width:1280,height:900});
  await appSection(page, 'Главная');
}
